#Requires -Version 5.1

<#
.SYNOPSIS
    Builds the FastPaper server jar and deploys it to <repo>\deploy.

.DESCRIPTION
    Removes every *.jar from the deploy folder, applies the patches, builds the
    Paperclip server jar with Gradle and copies the newest *paperclip*.jar from
    paper-server\build\libs into the deploy folder. The deploy folder is
    created when missing. Exits non-zero when the build fails or no jar is
    produced.

.PARAMETER SkipPatches
    Skip the applyPatches step and build from the current working tree.

.PARAMETER Clean
    Run "gradlew clean" before building.

.PARAMETER DryRun
    Print what would be deleted, run and copied without doing it.

.EXAMPLE
    PS> .\scripts\build-deploy.ps1
    Applies patches, builds and deploys the jar.

.EXAMPLE
    PS> .\scripts\build-deploy.ps1 -SkipPatches
    Rebuilds after editing paper-server sources without reapplying patches.

.EXAMPLE
    PS> .\scripts\build-deploy.ps1 -Clean -DryRun
    Shows the full clean build and deploy plan without running it.
#>
[CmdletBinding()]
param(
    [switch]$SkipPatches,
    [switch]$Clean,
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$deploy = Join-Path $root 'deploy'
$libs = Join-Path $root 'paper-server\build\libs'
$gradlew = Join-Path $root 'gradlew.bat'

function Invoke-Gradle([string[]]$GradleArgs) {
    Write-Host "> gradlew $($GradleArgs -join ' ')" -ForegroundColor Cyan
    if ($DryRun) { return }
    Push-Location $root
    try {
        & $gradlew @GradleArgs
        if ($LASTEXITCODE -ne 0) { throw "gradlew $($GradleArgs -join ' ') failed with exit code $LASTEXITCODE" }
    } finally {
        Pop-Location
    }
}

try {
    if (-not (Test-Path $deploy)) {
        Write-Host "Creating $deploy"
        if (-not $DryRun) { New-Item -ItemType Directory -Path $deploy | Out-Null }
    }

    # Deployed jars are build output and are regenerated by this script.
    $oldJars = @(Get-ChildItem -Path $deploy -Filter '*.jar' -File -ErrorAction SilentlyContinue)
    foreach ($jar in $oldJars) {
        Write-Host "Removing $($jar.FullName)"
        if (-not $DryRun) { Remove-Item -LiteralPath $jar.FullName -Force }
    }

    $buildStart = Get-Date
    if ($Clean) { Invoke-Gradle @('clean') }
    if (-not $SkipPatches) { Invoke-Gradle @('applyPatches') }
    Invoke-Gradle @('createPaperclipJar')

    if ($DryRun) {
        Write-Host "Would copy the newest *paperclip*.jar from $libs to $deploy"
        exit 0
    }

    # The jar base name follows rootProject.name, so match on the paperclip suffix only.
    $jar = Get-ChildItem -Path $libs -Filter '*paperclip*.jar' -File -ErrorAction SilentlyContinue |
        Sort-Object LastWriteTime -Descending | Select-Object -First 1
    if (-not $jar) { throw "No *paperclip*.jar found in $libs" }
    if ($jar.LastWriteTime -lt $buildStart) {
        Write-Warning "$($jar.Name) is older than this build; Gradle may have reused a cached output."
    }

    Copy-Item -LiteralPath $jar.FullName -Destination $deploy -Force
    Write-Host "Deployed $(Join-Path $deploy $jar.Name)" -ForegroundColor Green
    exit 0
} catch {
    Write-Error $_
    exit 1
}
